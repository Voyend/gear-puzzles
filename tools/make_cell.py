#!/usr/bin/env python3
"""Writes tools/gear_kit_cell.py: gear_kit.py without comments, docstrings and blank lines.

Gemini's code sandbox keeps no files between turns and has no network, so every run has to start with the whole
kit pasted in front of the level script. The cell version is the same code, much shorter.
Run it after every change of gear_kit.py:   python tools/make_cell.py      (needs Python 3.9+)"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


class Strip(ast.NodeTransformer):
    def _strip(self, node):
        self.generic_visit(node)
        body = node.body
        if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) and isinstance(body[0].value.value, str):
            body = body[1:]
        node.body = body or [ast.Pass()]
        return node

    visit_Module = visit_ClassDef = visit_FunctionDef = _strip


def main():
    src = open(os.path.join(HERE, "gear_kit.py")).read()
    tree = Strip().visit(ast.parse(src))
    ast.fix_missing_locations(tree)
    out = "# gear_kit (cell version: generated by make_cell.py, do not edit)\n" + ast.unparse(tree) + "\n"
    cut = out.index("if __name__ == '__main__':")      # the command line is not needed in a cell
    out = out[:cut].rstrip() + "\n"
    path = os.path.join(HERE, "gear_kit_cell.py")
    with open(path, "w") as f:
        f.write(out)
    print("wrote %s (%d lines, %d characters)" % (path, out.count("\n"), len(out)))


if __name__ == "__main__":
    sys.exit(main())
